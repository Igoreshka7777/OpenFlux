var gate = NetworkPathEventGate()
let wifi = gate.begin()
let mobile = gate.begin()
precondition(!gate.finish(wifi), "Delayed Wi-Fi must not overwrite cellular")
precondition(gate.finish(mobile))
precondition(!gate.finish(mobile), "Duplicate callback must not reconnect twice")
let returningWiFi = gate.begin()
precondition(gate.finish(returningWiFi), "Fallback must finish a Wi-Fi event")
precondition(!gate.finish(returningWiFi), "SSID arriving after fallback must be ignored")
let stopping = gate.begin()
gate.invalidate()
precondition(!gate.finish(stopping), "Stop must invalidate pending recovery")
for _ in 0..<1000 {
    let old = gate.begin()
    let newest = gate.begin()
    precondition(!gate.finish(old))
    precondition(gate.finish(newest))
}
print("PASS: stale Wi-Fi, mobile handover, fallback, duplicate, stop, rapid flapping")
